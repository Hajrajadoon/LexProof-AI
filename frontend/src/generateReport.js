
import { jsPDF } from "jspdf";

function addSection(doc, title, items, y) {
  if (!items || items.length === 0) return y;

  if (y > 255) {
    doc.addPage();
    y = 20;
  }

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text(title, 15, y);
  y += 8;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  const list = Array.isArray(items) ? items : [items];

  for (const item of list) {
    const text =
      typeof item === "string"
        ? item
        : item?.description || item?.text || JSON.stringify(item);

    const lines = doc.splitTextToSize(`• ${text}`, 175);

    if (y + lines.length * 5 > 275) {
      doc.addPage();
      y = 20;
    }

    doc.text(lines, 15, y);
    y += lines.length * 5 + 3;
  }

  return y + 5;
}

export function generateReport(analysis) {
  if (!analysis) return;

  const doc = new jsPDF();
  const report = analysis.ai_report || {};
  let y = 20;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("LexProof AI", 15, y);
  y += 10;

  doc.setFontSize(14);
  doc.text("Legal Document Analysis Report", 15, y);
  y += 10;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  const filename =
    analysis.filename || analysis.document_name || "Untitled document";

  doc.text(
    doc.splitTextToSize(`Document: ${filename}`, 175),
    15,
    y
  );
  y += 10;

  doc.text(`Generated: ${new Date().toLocaleString()}`, 15, y);
  y += 10;

  y = addSection(
    doc,
    "Document Summary",
    report.summary || analysis.document_summary || "No summary available.",
    y
  );

  y = addSection(doc, "Document Type", report.document_type, y);
  y = addSection(doc, "Key Obligations", report.key_obligations, y);
  y = addSection(doc, "Risk Findings", report.risk_findings, y);
  y = addSection(
    doc,
    "Questions for a Lawyer",
    report.questions_for_lawyer,
    y
  );

  y = addSection(
    doc,
    "SHA-256 Document Hash",
    analysis.sha256 || analysis.file_hash || "Not available",
    y
  );

  const onChain = analysis.chain_status === "success";
  y = addSection(
    doc,
    "Blockchain Verification",
    onChain
      ? [
          `Status: Registered on the Casper blockchain (${analysis.chain_network || "casper-test"})`,
          `Transaction: ${analysis.chain_tx_hash || "n/a"}`,
          `Contract: ${analysis.chain_contract_hash || "n/a"}`,
          `Registered by account: ${analysis.chain_account || "n/a"}`,
          `Registered at: ${analysis.chain_registered_at || "n/a"}`,
          "Only the SHA-256 hash is stored on-chain, not the document contents.",
        ].join("\n")
      : "Not registered on a blockchain.",
    y
  );

  addSection(
    doc,
    "Important Disclaimer",
    "This report is generated by an AI system for informational purposes only. It may contain errors or omissions and is not legal advice. Consult a qualified lawyer before making legal decisions.",
    y
  );

  const safeName = filename
    .replace(/\.pdf$/i, "")
    .replace(/[^a-z0-9_-]/gi, "_")
    .slice(0, 80);

  doc.save(`LexProof_Report_${safeName || "Document"}.pdf`);
}
